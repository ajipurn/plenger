import type { Rule } from "../rules/model.ts";

/** The rule list for the terminal: id, highest severity, name and what each maps to. */
export function formatRules(rules: Rule[]): string {
  const lines: string[] = [];
  for (const rule of rules) {
    const cwe = rule.cwe.map((id) => `CWE-${id}`);
    lines.push(
      `${rule.id}  ${rule.severity.padEnd(8)}  ${rule.name}`,
      `         ${rule.title}`,
      `         ${[...rule.owasp, ...cwe].join(", ")}`,
      "",
    );
  }
  lines.push(
    "OWASP: LLMxx:2025 is the Top 10 for LLM Applications 2025; ASIxx the Top 10 for Agentic Applications 2026.",
  );
  return `${lines.join("\n")}\n`;
}

const OWASP_LINK: Record<string, string> = {
  "LLM01:2025": "https://genai.owasp.org/llmrisk/llm01-prompt-injection/",
  "LLM02:2025": "https://genai.owasp.org/llmrisk/llm022025-sensitive-information-disclosure/",
  "LLM03:2025": "https://genai.owasp.org/llmrisk/llm032025-supply-chain/",
  "LLM05:2025": "https://genai.owasp.org/llmrisk/llm052025-improper-output-handling/",
  "LLM06:2025": "https://genai.owasp.org/llmrisk/llm062025-excessive-agency/",
  "LLM07:2025": "https://genai.owasp.org/llmrisk/llm072025-system-prompt-leakage/",
  "LLM08:2025": "https://genai.owasp.org/llmrisk/llm082025-vector-and-embedding-weaknesses/",
  "LLM10:2025": "https://genai.owasp.org/llmrisk/llm102025-unbounded-consumption/",
};

/** The rule reference in docs/RULES.md, generated from the catalog. */
export function rulesMarkdown(rules: Rule[]): string {
  const owasp = (id: string) => (OWASP_LINK[id] === undefined ? id : `[${id}](${OWASP_LINK[id]})`);
  const cwe = (id: number) => `[CWE-${id}](https://cwe.mitre.org/data/definitions/${id}.html)`;
  const lines = [
    "# Rules",
    "",
    "<!-- Generated by `node scripts/rules-doc.ts` from src/rules/catalog.ts. Do not edit by hand. -->",
    "",
    "Each finding names one of these rules. Severity is the highest a rule reports; a",
    "single finding can be rated lower, for example when plenger saw an input check or",
    "an approval step. OWASP ids refer to the [Top 10 for LLM Applications",
    "2025](https://genai.owasp.org/llm-top-10/) (`LLMxx:2025`) and the [Top 10 for Agentic",
    "Applications 2026](https://genai.owasp.org/resource/owasp-top-10-for-agentic-applications-for-2026/)",
    "(`ASIxx`).",
    "",
    "| Rule | Severity | Finds |",
    "| --- | --- | --- |",
    ...rules.map(
      (rule) =>
        `| [${rule.id}](#${rule.id.toLowerCase()}-${rule.name}) | ${rule.severity} | ${rule.title} |`,
    ),
  ];
  for (const rule of rules) {
    lines.push(
      "",
      `## ${rule.id} ${rule.name}`,
      "",
      `**${rule.title}.** Severity up to ${rule.severity}.`,
      "",
      rule.description,
      "",
      `**Fix:** ${rule.remediation}`,
      "",
      `**Maps to:** ${[...rule.owasp.map(owasp), ...rule.cwe.map(cwe)].join(", ")}`,
    );
  }
  return `${lines.join("\n")}\n`;
}
